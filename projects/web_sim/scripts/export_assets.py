"""Export the MuJoCo twin of the wallerobot into the web app (projects/web_sim/web/public/model/).

    .venv/Scripts/python.exe projects/web_sim/scripts/export_assets.py

Source of truth stays where it is: the MJCF is generated by projects/sim_mirror/scripts/build_mjcf.py from the URDF in
hardware/wallerobot_v0_1/. This script only copies it for the browser and adds web-only bits to the COPY:
  * meshdir rewritten to "meshes", only the referenced STL files are copied;
  * one site per arm, `left_ee` / `right_ee`, half-way between the fixed- and the moving-jaw tip (the IK target);
  * poses.json: home pose (neck poses.home target + arm rest pose, from the calibration files) and the joint table.
Run it again whenever build_mjcf.py or the calibration changes. Routes (web/public/routes/*.json) are hand-written.
"""
import json
import math
import re
import shutil
import sys
from pathlib import Path

import mujoco
import numpy as np

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "projects/sim_mirror/models"
OUT = ROOT / "projects/web_sim/web/public/model"
sys.path.insert(0, str(ROOT / "projects/sim_mirror/scripts"))
import calib  # noqa: E402


def ee_site_pos(model_xml: Path, side: str) -> np.ndarray:
    """Mid-point of the two jaw tips with the gripper closed (q=0), in the fixed-jaw body frame."""
    m = mujoco.MjModel.from_xml_path(str(model_xml)); d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    a = d.site(f"{side}_fixed_jaw_tip").xpos.copy(); b = d.site(f"{side}_moving_jaw_tip").xpos.copy()
    body = m.body(f"{side}_arm_fixed_jaw").id
    R = d.xmat[body].reshape(3, 3); p = d.xpos[body]
    return R.T @ ((a + b) / 2 - p)


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "meshes").mkdir(parents=True)
    robot = (SRC / "wallerobot_static.xml").read_text(encoding="utf-8")
    meshdir = re.search(r'meshdir="([^"]+)"', robot).group(1)
    mesh_src = (SRC / meshdir).resolve()
    robot = robot.replace(f'meshdir="{meshdir}"', 'meshdir="meshes"')
    files = sorted(set(re.findall(r'<mesh [^>]*file="([^"]+)"', robot)))
    for f in files:
        shutil.copy2(mesh_src / f, OUT / "meshes" / f)

    for side in ("left", "right"):
        p = ee_site_pos(SRC / "wallerobot_static.xml", side)
        anchor = f'<site name="{side}_fixed_jaw_tip"'
        i = robot.index(anchor)
        robot = (robot[:i] + f'<site name="{side}_ee" size="0.006" pos="{p[0]:.5f} {p[1]:.5f} {p[2]:.5f}" group="4" />\n'
                 + " " * 16 + robot[i:])
    robot = robot.replace("<!-- GENERATED by", "<!-- WEB COPY (projects/web_sim/scripts/export_assets.py) of a file GENERATED by", 1)
    (OUT / "wallerobot_static.xml").write_text(robot, encoding="utf-8")
    shutil.copy2(SRC / "scene.xml", OUT / "scene.xml")

    # home pose: neck = poses.home target (clamped into the limits), arms = the standard rest pose
    neck = json.loads(calib.NECK_CAL.read_text(encoding="utf-8"))["poses"]["home"]["target_ticks"]
    arms = json.loads(calib.ARM_CAL.read_text(encoding="utf-8"))["rest_pose"]["ticks"]
    home = {n: calib.tick_to_rad(n, t) for n, t in {**neck, **arms}.items()}

    m = mujoco.MjModel.from_xml_path(str(OUT / "scene.xml"))
    joints = []
    for j in range(m.njnt):
        n = m.joint(j).name; lo, hi = m.jnt_range[j]
        q = float(np.clip(home[n], lo, hi))
        joints.append({"name": n, "lower": float(lo), "upper": float(hi), "home": round(q, 5)})
    (OUT / "poses.json").write_text(json.dumps({
        "source": "neck_calibration.json poses.home target_ticks + arm_calibration.json rest_pose (clamped into the MJCF ranges)",
        "joints": joints}, indent=1), encoding="utf-8")
    # the browser writes these into MuJoCo's in-memory filesystem before loading scene.xml
    listing = ["scene.xml", "wallerobot_static.xml"] + [f"meshes/{f}" for f in files]
    (OUT / "manifest.json").write_text(json.dumps({"entry": "scene.xml", "files": listing}, indent=0), encoding="utf-8")
    size = sum(f.stat().st_size for f in (OUT / "meshes").iterdir())
    print(f"exported {len(files)} meshes ({size / 1e6:.1f} MB), {m.njnt} joints, {m.nu} actuators -> {OUT}")
    for jt in joints:
        print(f"  {jt['name']:24s} home {math.degrees(jt['home']):+7.1f}°  [{math.degrees(jt['lower']):+7.1f}, {math.degrees(jt['upper']):+7.1f}]")


if __name__ == "__main__":
    main()
