"""Print the joint table of the wallerobot (18 joints) as Markdown, straight from the calibration files and the URDF.

    .venv/Scripts/python.exe hardware/wallerobot_v0_1/joint_table.py            # -> stdout
    .venv/Scripts/python.exe hardware/wallerobot_v0_1/joint_table.py --write    # -> JOINTS.md + docs/robot_design.md section 4

--write also refreshes section 4 of docs/robot_design.md (between the JOINTS markers), so the documented numbers are the ones the code uses.
"""
import json
import math
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "projects/sim_mirror/scripts"))
import calib  # noqa: E402

NOTES = {
    "shoulder_lift": "rests on the fold stop; no EEPROM limit (0..4095); encoder wrap 180° from rest lies in the travel → torque refused until Homing_Offset is re-centred",
    "elbow_flex": "same as shoulder_lift",
    "gripper": "parallel gripper (model: stock SO101 jaw); linear closed..open",
    "neck_j1": "base pan",
    "neck_j2": "neck lift, rests on its fold stop past the limit (home target = limit); zero from the IMU demo fit",
    "neck_j3": "elbow, rests past the limit; zero from the wrist/upper-arm fold contact",
    "neck_j4": "side swing, axis ⟂ J3 (new link STL)",
    "neck_j5": "camera roll; Phase 92 batch (ids 9-11)",
    "neck_j6": "camera tilt; drives to a wrong target with torque on → keep limp (cause open)",
}


def main():
    urdf = ET.parse(calib.URDF).getroot()
    lim = {j.get("name"): j.find("limit") for j in urdf.iter("joint") if j.get("type") == "revolute"}
    neck = json.loads(calib.NECK_CAL.read_text(encoding="utf-8")); home = neck["poses"]["home"]
    arms = json.loads(calib.ARM_CAL.read_text(encoding="utf-8")); rest = arms["rest_pose"]["ticks"]
    lines = ["<!-- generated by hardware/wallerobot_v0_1/joint_table.py — do not edit by hand -->",
             "| joint | bus / ID | sign | zero tick | EEPROM range | URDF limit (deg) | rest / home (deg) | notes |",
             "|---|---|---|---|---|---|---|---|"]
    for n in calib.ORDER:
        c = calib.CAL[n]; L = lim.get(n)
        lo, hi = (math.degrees(float(L.get("lower"))), math.degrees(float(L.get("upper")))) if L is not None else (None, None)
        tick = home["ticks"].get(n) if n.startswith("neck") else rest.get(n)
        pose = f"{math.degrees(calib.tick_to_rad(n, tick)):+.1f}" if tick is not None else ""
        if c["type"] == "gripper":
            z = f"closed {c['closed_tick']} / open {c['open_tick']}"; sg = "lin"
        else:
            z = str(c["zero_tick"]); sg = "+1" if c["sign"] > 0 else "−1"
        note = next((v for k, v in NOTES.items() if n.endswith(k)), "")
        lines.append(f"| `{n}` | {c['port']} / {c['id']} | {sg} | {z} | {c['range_min']}..{c['range_max']} | "
                     f"{lo:+.1f} .. {hi:+.1f} | {pose} | {note} |")
    lines.append("")
    lines.append("Angle convention: `q = sign · (Present_Position − zero_tick) · 360/4096` (Present_Position includes the EEPROM "
                 "Homing_Offset); grippers are linear from closed_tick..open_tick to closed..open rad. Rest/home = arms' standard "
                 "rest pose (`arm_calibration.json` rest_pose) and the neck `poses.home` (`neck_calibration.json`).")
    out = "\n".join(lines) + "\n"
    if "--write" in sys.argv:
        (HERE / "JOINTS.md").write_text("# wallerobot v0.1 — joints\n\n" + out, encoding="utf-8"); print("wrote", HERE / "JOINTS.md")
        doc = ROOT / "docs/robot_design.md"
        if not doc.exists():                                        # public repo: no lab design doc
            return
        s = doc.read_text(encoding="utf-8")
        a, b = s.index("<!-- JOINTS:BEGIN -->") + len("<!-- JOINTS:BEGIN -->\n"), s.index("<!-- JOINTS:END -->")
        table = out.split("\n\nAngle convention")[0] + "\n"        # the doc has its own (Chinese) convention paragraph
        doc.write_text(s[:a] + table + s[b:], encoding="utf-8"); print("updated", doc, "section 4")
    else:
        print(out)


if __name__ == "__main__":
    main()
